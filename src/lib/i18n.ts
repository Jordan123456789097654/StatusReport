export type Strings = Record<StringKey, string>;

export function getStrings(locale: string, overrides?: Partial<Record<string, Partial<Record<StringKey, string>>>> | null): Strings {
  const l = (locale in LOCALES ? locale : "en") as Locale;
  return { ...en, ...dict[l], ...(overrides?.[l] || {}) } as Strings;
}
